class AnatomyPacketError(RuntimeError):
    """Raised when packet preparation violates the frozen protocol."""


def _derived_seed(seed: int, purpose: str) -> int:
    if isinstance(seed, bool) or not isinstance(seed, (int, np.integer)):
        raise AnatomyPacketError('Random seed must be an integer.')
    material = f'm4-2b3|{int(seed)}|{purpose}'.encode('utf-8')
    return int.from_bytes(hashlib.sha256(material).digest()[:16], 'big')


def _rng(seed: int, purpose: str) -> np.random.Generator:
    return np.random.Generator(np.random.PCG64(_derived_seed(seed, purpose)))


def _require_case_arrays(case: Mapping, subject_id: str):
    try:
        linear = np.asarray(case['support_linear'], dtype=np.int64)
        locations = np.asarray(case['support_locations_mm'], dtype=np.float64)
        score = np.asarray(case['score'], dtype=np.float64)
    except (KeyError, TypeError, ValueError, OverflowError) as error:
        raise AnatomyPacketError(f'{subject_id} token arrays are malformed.') from error
    if linear.ndim != 1 or linear.size < POINTS_PER_PATIENT:
        raise AnatomyPacketError(
            f'{subject_id} requires at least {POINTS_PER_PATIENT} support tokens.'
        )
    if locations.shape != (linear.size, 3) or score.shape != (linear.size,):
        raise AnatomyPacketError(f'{subject_id} token arrays are not aligned.')
    if len(np.unique(linear)) != linear.size:
        raise AnatomyPacketError(f'{subject_id} support linear IDs must be unique.')
    if not np.all(np.isfinite(locations)) or not np.all(np.isfinite(score)):
        raise AnatomyPacketError(f'{subject_id} token arrays must be finite.')
    if np.any(score <= 0.0) or np.any(score >= 1.0):
        raise AnatomyPacketError(f'{subject_id} scores must lie in the open unit interval.')
    return linear, locations, score


def sample_patient_tokens(case: Mapping, subject_id: str, seed: int = RANDOM_SEED) -> list:
    """Select the frozen 10 HIGH and uniform 10 non-HIGH CONTROL tokens."""
    linear, locations, score = _require_case_arrays(case, subject_id)
    score_order = np.lexsort((linear, -score))
    high_indices = score_order[:HIGH_COUNT_PER_PATIENT]
    high_mask = np.zeros(linear.size, dtype=bool)
    high_mask[high_indices] = True
    control_candidates = np.flatnonzero(~high_mask)
    control_indices = _rng(seed, f'CONTROL|{subject_id}').choice(
        control_candidates,
        size=CONTROL_COUNT_PER_PATIENT,
        replace=False,
    )

    selected = []
    for group, indices in (('HIGH', high_indices), ('CONTROL', control_indices)):
        for index in indices:
            row = int(index)
            selected.append(
                {
                    'subject_id': subject_id,
                    'group': group,
                    'support_linear_id': int(linear[row]),
                    'support_location_mm': [float(value) for value in locations[row]],
                    'score': float(score[row]),
                }
            )
    permutation = _rng(seed, f'POINT|{subject_id}').permutation(len(selected))
    return [selected[int(index)] for index in permutation]


def build_blinded_assignments(cases: Mapping[str, Mapping], seed: int = RANDOM_SEED) -> dict:
    """Assign deterministic anonymous case/point IDs to all 200 selected tokens."""
    if set(cases) != set(CLEAN10_SUBJECT_IDS) or len(cases) != len(CLEAN10_SUBJECT_IDS):
        raise AnatomyPacketError('Cases must contain exactly the ten frozen clean10 patients.')
    case_permutation = _rng(seed, 'CASE').permutation(len(CLEAN10_SUBJECT_IDS))
    case_order = [CLEAN10_SUBJECT_IDS[int(index)] for index in case_permutation]
    records = []
    for case_number, subject_id in enumerate(case_order, start=1):
        anonymous_case = f'CASE{case_number:02d}'
        selected = sample_patient_tokens(cases[subject_id], subject_id, seed)
        if len(selected) != POINTS_PER_PATIENT:
            raise AnatomyPacketError('Internal selected-point count mismatch.')
        for point_number, record in enumerate(selected, start=1):
            anonymous_point = f'{anonymous_case}_POINT{point_number:03d}'
            records.append(
                {
                    'anonymous_case': anonymous_case,
                    'anonymous_point': anonymous_point,
                    'subject_id': subject_id,
                    'defect_id': CANONICAL_DEFECT,
                    'group': record['group'],
                    'support_linear_id': record['support_linear_id'],
                    'support_location_mm': record['support_location_mm'],
                    'score': record['score'],
                }
            )
    validate_hidden_records(records)
    return {'case_order': case_order, 'records': records}


def validate_hidden_records(records: Sequence[Mapping]) -> None:
    if len(records) != len(CLEAN10_SUBJECT_IDS) * POINTS_PER_PATIENT:
        raise AnatomyPacketError('Hidden key must contain exactly 200 points.')
    point_ids = [str(record.get('anonymous_point', '')) for record in records]
    if len(set(point_ids)) != len(point_ids):
        raise AnatomyPacketError('Hidden anonymous point IDs must be unique.')
    for subject_id in CLEAN10_SUBJECT_IDS:
        patient = [record for record in records if record.get('subject_id') == subject_id]
        groups = [record.get('group') for record in patient]
        if len(patient) != POINTS_PER_PATIENT:
            raise AnatomyPacketError(f'{subject_id} must have exactly 20 selected points.')
        if groups.count('HIGH') != HIGH_COUNT_PER_PATIENT:
            raise AnatomyPacketError(f'{subject_id} must have exactly 10 HIGH points.')
        if groups.count('CONTROL') != CONTROL_COUNT_PER_PATIENT:
            raise AnatomyPacketError(f'{subject_id} must have exactly 10 CONTROL points.')
        high_ids = {
            int(record['support_linear_id'])
            for record in patient
            if record.get('group') == 'HIGH'
        }
        control_ids = {
            int(record['support_linear_id'])
            for record in patient
            if record.get('group') == 'CONTROL'
        }
        if high_ids & control_ids:
            raise AnatomyPacketError(f'{subject_id} HIGH and CONTROL points overlap.')


def _extract_external_surface_sitk(ct_volume) -> np.ndarray:
    """Extract the existing six-connected boundary-air external CT surface."""
    try:
        import SimpleITK as sitk
    except ModuleNotFoundError as error:
        raise AnatomyPacketError('SimpleITK is required for real CT packet generation.') from error
    volume = np.asarray(ct_volume)
    if volume.ndim != 3 or any(size <= 0 for size in volume.shape):
        raise AnatomyPacketError('CT volume must be a non-empty 3D array.')
    foreground = volume > float(CT_FOREGROUND_HU)
    labels = sitk.GetArrayFromImage(
        sitk.ConnectedComponent(
            sitk.GetImageFromArray((~foreground).astype(np.uint8)),
            False,
        )
    )
    boundary_labels = set()
    for face in (
        labels[0, :, :],
        labels[-1, :, :],
        labels[:, 0, :],
        labels[:, -1, :],
        labels[:, :, 0],
        labels[:, :, -1],
    ):
        boundary_labels.update(int(value) for value in np.unique(face) if int(value) != 0)
    outside_air = np.zeros(volume.shape, dtype=bool)
    for label in sorted(boundary_labels):
        outside_air |= labels == label
    dilated = outside_air.copy()
    dilated[1:, :, :] |= outside_air[:-1, :, :]
    dilated[:-1, :, :] |= outside_air[1:, :, :]
    dilated[:, 1:, :] |= outside_air[:, :-1, :]
    dilated[:, :-1, :] |= outside_air[:, 1:, :]
    dilated[:, :, 1:] |= outside_air[:, :, :-1]
    dilated[:, :, :-1] |= outside_air[:, :, 1:]
    surface = foreground & dilated
    surface[0, :, :] |= foreground[0, :, :]
    surface[-1, :, :] |= foreground[-1, :, :]
    surface[:, 0, :] |= foreground[:, 0, :]
    surface[:, -1, :] |= foreground[:, -1, :]
    surface[:, :, 0] |= foreground[:, :, 0]
    surface[:, :, -1] |= foreground[:, :, -1]
    return surface


def _read_case(data_root: Path, subject_id: str) -> dict:
    ct_path = data_root / subject_id / 'defects' / CANONICAL_DEFECT / 'ct_defect.nrrd'
    if not ct_path.is_file():
        raise AnatomyPacketError(f'Missing canonical defective CT for {subject_id}: {ct_path}')
    ct = read_ct_nrrd(ct_path)
    if tuple(ct.get('array_axis_order', ())) != ('z', 'y', 'x'):
        raise AnatomyPacketError('CT array storage order must be [z,y,x].')
    if tuple(ct.get('image_index_convention', ())) != ('x', 'y', 'z'):
        raise AnatomyPacketError('CT image index convention must be [x,y,z].')
    volume = np.asarray(ct['ct_volume'])
    external_surface = _extract_external_surface_sitk(volume)
    support = build_ct_support_20mm(
        external_surface,
        ct['ct_spacing'],
        ct['ct_origin'],
        ct['ct_direction'],
        volume_shape_zyx=volume.shape,
        physical_unit='mm',
        coordinate_system='LPS',
    )
    score = compute_continuous_osseous_support_score(
        volume,
        ct['ct_spacing'],
        ct['ct_origin'],
        ct['ct_direction'],
        support['ct_support_phys_20mm'],
        CENTER_HU,
        TAU_HU,
        RADIUS_MM,
    )
    return {
        'ct': ct,
        'support_linear': np.asarray(support['ct_support_linear_20mm'], dtype=np.int64),
        'support_locations_mm': np.asarray(support['ct_support_phys_20mm'], dtype=np.float64),
        'score': np.asarray(score, dtype=np.float64),
    }


def _sample_physical_plane(
    ct: Mapping,
    center_mm: Sequence[float],
    view: str,
) -> np.ndarray:
    volume = np.asarray(ct['ct_volume'])
    spacing = np.asarray(ct['ct_spacing'], dtype=np.float64)
    origin = np.asarray(ct['ct_origin'], dtype=np.float64)
    direction = np.asarray(ct['ct_direction'], dtype=np.float64).reshape(3, 3)
    center = np.asarray(center_mm, dtype=np.float64)
    if center.shape != (3,) or not np.all(np.isfinite(center)):
        raise AnatomyPacketError('Review point must be a finite physical [x,y,z] location.')
    size = int(round(CONTEXT_MM / OUTPUT_PIXEL_MM)) + 1
    offsets = np.linspace(-0.5 * CONTEXT_MM, 0.5 * CONTEXT_MM, size)
    column, row = np.meshgrid(offsets, offsets, indexing='xy')
    physical = np.empty((size, size, 3), dtype=np.float64)
    if view == 'axial':
        physical[..., 0] = center[0] + column
        physical[..., 1] = center[1] - row
        physical[..., 2] = center[2]
    elif view == 'coronal':
        physical[..., 0] = center[0] + column
        physical[..., 1] = center[1]
        physical[..., 2] = center[2] - row
    elif view == 'sagittal':
        physical[..., 0] = center[0]
        physical[..., 1] = center[1] + column
        physical[..., 2] = center[2] - row
    else:
        raise AnatomyPacketError(f'Unsupported review view: {view!r}.')
    image_affine = direction @ np.diag(spacing)
    try:
        index_xyz = np.linalg.solve(
            image_affine,
            (physical.reshape(-1, 3) - origin[np.newaxis, :]).T,
        ).T
    except np.linalg.LinAlgError as error:
        raise AnatomyPacketError('CT image geometry is not invertible.') from error
    nearest = np.rint(index_xyz).astype(np.int64)
    size_xyz = np.asarray(volume.shape[::-1], dtype=np.int64)
    valid = np.all((nearest >= 0) & (nearest < size_xyz[np.newaxis, :]), axis=1)
    sampled = np.full(nearest.shape[0], OUTSIDE_HU, dtype=np.float64)
    inside = nearest[valid]
    sampled[valid] = volume[inside[:, 2], inside[:, 1], inside[:, 0]]
    return sampled.reshape(size, size)


def _window_with_crosshair(plane_hu: np.ndarray) -> np.ndarray:
    lower = BONE_WINDOW_LEVEL_HU - 0.5 * BONE_WINDOW_WIDTH_HU
    scaled = (np.asarray(plane_hu, dtype=np.float64) - lower) / BONE_WINDOW_WIDTH_HU
    gray = np.rint(np.clip(scaled, 0.0, 1.0) * 255.0).astype(np.uint8)
    rgb = np.repeat(gray[..., np.newaxis], 3, axis=2)
    center_y = rgb.shape[0] // 2
    center_x = rgb.shape[1] // 2
    for delta in range(-7, 8):
        if abs(delta) <= 2:
            continue
        rgb[center_y, center_x + delta] = (255, 0, 0)
        rgb[center_y + delta, center_x] = (255, 0, 0)
    rgb[center_y, center_x] = (255, 0, 0)
    return rgb


def render_review_png(ct: Mapping, center_mm: Sequence[float], view: str, path: Path) -> None:
    try:
        import SimpleITK as sitk
    except ModuleNotFoundError as error:
        raise AnatomyPacketError('SimpleITK is required to write reviewer PNG files.') from error
    rgb = _window_with_crosshair(_sample_physical_plane(ct, center_mm, view))
    image = sitk.GetImageFromArray(rgb, isVector=True)
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        sitk.WriteImage(image, str(path), True)
    except Exception as error:
        raise AnatomyPacketError(f'Could not write review PNG {path}: {error}') from error
    if not path.is_file() or path.stat().st_size <= 0:
        raise AnatomyPacketError(f'Review PNG was not created: {path}')


def reviewer_rows_from_hidden(records: Sequence[Mapping]) -> tuple:
    blinded_rows = []
    reviewer_rows = []
    for record in records:
        anonymous_case = str(record['anonymous_case'])
        anonymous_point = str(record['anonymous_point'])
        image_stem = f'blinded_images/{anonymous_point}'
        blinded_rows.append(
            {
                'anonymous_case': anonymous_case,
                'anonymous_point': anonymous_point,
                'axial_image': f'{image_stem}_axial.png',
                'coronal_image': f'{image_stem}_coronal.png',
                'sagittal_image': f'{image_stem}_sagittal.png',
            }
        )
        reviewer_rows.append(
            {
                'anonymous_case': anonymous_case,
                'anonymous_point': anonymous_point,
                'anatomical_category': '',
                'reviewer_confidence': '',
                'comments': '',
            }
        )
    return blinded_rows, reviewer_rows


def _write_csv(path: Path, fieldnames: Sequence[str], rows: Sequence[Mapping]) -> None:
    with path.open('w', newline='', encoding='utf-8') as stream:
        writer = csv.DictWriter(stream, fieldnames=fieldnames, extrasaction='raise')
        writer.writeheader()
        writer.writerows(rows)


